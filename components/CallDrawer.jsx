'use client';
import clsx from 'clsx';
import { Bot, User, Info, PlayCircle } from 'lucide-react';
import { useApi } from '@/lib/useApi';
import { useSocketEvent } from '@/lib/socket';
import { Drawer, Spinner, StatusPill, OutcomePill, Badge } from './ui';
import { fmtDateTime, fmtDuration, fmtMs, ACTION_LABEL } from '@/lib/format';

function Row({ label, children }) {
  return (
    <div className="flex items-start justify-between gap-4 py-1.5 text-[13px]">
      <span className="text-ink-3">{label}</span>
      <span className="text-right text-ink">{children}</span>
    </div>
  );
}

export function CallDrawer({ callId, onClose }) {
  const { data, loading, mutate } = useApi(callId ? `/calls/${callId}` : null);
  useSocketEvent('call:transcript', ({ callId: id, entry }) => {
    if (id === callId) mutate((d) => d && { ...d, call: { ...d.call, transcript: [...(d.call.transcript || []), entry] } });
  });
  const c = data?.call;

  return (
    <Drawer open={Boolean(callId)} onClose={onClose} title={c ? c.name || c.phone : 'Call details'}>
      {loading && !c ? (
        <div className="flex justify-center py-10">
          <Spinner />
        </div>
      ) : c ? (
        <div className="space-y-6">
          <section>
            <div className="mb-2 flex flex-wrap items-center gap-2">
              <StatusPill status={c.status} />
              {c.selection && <Badge tone="violet">{ACTION_LABEL[c.selection]}</Badge>}
              {c.callbackRequested && <Badge tone="amber">Callback requested</Badge>}
              {c.optOut && <Badge tone="red">Opted out</Badge>}
            </div>
            <div className="divide-y divide-line rounded-lg border border-line px-3">
              <Row label="Phone">{c.phone}</Row>
              <Row label="Campaign">{c.campaign?.name || 'Test call'}</Row>
              <Row label="Attempt">{c.attempt}</Row>
              <Row label="Started">{fmtDateTime(c.answeredAt || c.initiatedAt)}</Row>
              <Row label="Ended">{fmtDateTime(c.endedAt)}</Row>
              <Row label="Duration">{fmtDuration(c.duration)}</Row>
              <Row label="Keys pressed">{c.dtmf?.length ? c.dtmf.map((d) => d.digit).join(', ') : '—'}</Row>
              <Row label="WhatsApp">
                <OutcomePill value={c.whatsapp?.status} />
              </Row>
              <Row label="Support transfer">
                <OutcomePill value={c.transfer?.status} />
                {c.transfer?.duration ? <span className="ml-1 text-ink-3">({fmtDuration(c.transfer.duration)})</span> : null}
              </Row>
              <Row label="Avg response latency">{fmtMs(c.latency?.avgResponseMs)}</Row>
              <Row label="Greeting latency">{fmtMs(c.latency?.greetingMs)}</Row>
              {c.endReason && <Row label="End reason">{c.endReason}</Row>}
              {c.error && <Row label="Error"><span className="text-red-600">{c.error}</span></Row>}
            </div>
            {c.recordingUrl && (
              <a href={c.recordingUrl} target="_blank" rel="noreferrer" className="mt-3 inline-flex items-center gap-1.5 text-[13px] font-medium text-brand-600 hover:underline">
                <PlayCircle className="h-4 w-4" /> Open call recording
              </a>
            )}
          </section>

          <section>
            <h4 className="mb-2 text-[13px] font-semibold">AI summary</h4>
            {c.summary ? (
              <div className="rounded-lg bg-panel p-3 text-[13px] text-ink-2">
                <p>{c.summary}</p>
                <div className="mt-2 flex flex-wrap gap-1.5">
                  {c.disposition && <Badge tone="blue">{c.disposition.replace(/_/g, ' ')}</Badge>}
                  {c.sentiment && <Badge>{c.sentiment}</Badge>}
                </div>
                {c.followUp && c.followUp !== 'none' && <p className="mt-2 text-[12px] text-ink-3">Next step: {c.followUp}</p>}
              </div>
            ) : (
              <p className="text-[12px] text-ink-3">Generated by the LangGraph pipeline after the call ends.</p>
            )}
          </section>

          {c.questions?.length > 0 && (
            <section>
              <h4 className="mb-2 text-[13px] font-semibold">Customer questions</h4>
              <ul className="space-y-1.5">
                {c.questions.map((q, i) => (
                  <li key={i} className="flex items-start justify-between gap-3 rounded-lg border border-line px-3 py-2 text-[13px]">
                    <span className="text-ink">{q.question}</span>
                    {q.answered ? <Badge tone="green">Answered</Badge> : <Badge tone="amber">Not answered</Badge>}
                  </li>
                ))}
              </ul>
            </section>
          )}

          <section>
            <h4 className="mb-2 text-[13px] font-semibold">Transcript</h4>
            {c.transcript?.length ? (
              <ul className="space-y-2">
                {c.transcript.map((t, i) => (
                  <li key={i} className={clsx('flex gap-2', t.role === 'customer' && 'flex-row-reverse')}>
                    <span className={clsx('mt-0.5 flex h-6 w-6 shrink-0 items-center justify-center rounded-full', t.role === 'agent' ? 'bg-brand-100 text-brand-700' : t.role === 'customer' ? 'bg-blue-50 text-blue-700' : 'bg-panel text-ink-3')}>
                      {t.role === 'agent' ? <Bot className="h-3.5 w-3.5" /> : t.role === 'customer' ? <User className="h-3.5 w-3.5" /> : <Info className="h-3.5 w-3.5" />}
                    </span>
                    <p className={clsx('max-w-[80%] rounded-xl px-3 py-2 text-[13px]', t.role === 'customer' ? 'bg-blue-50 text-ink' : t.role === 'agent' ? 'bg-panel text-ink' : 'text-[12px] italic text-ink-3')}>
                      {t.text}
                    </p>
                  </li>
                ))}
              </ul>
            ) : (
              <p className="text-[12px] text-ink-3">No transcript captured.</p>
            )}
          </section>

          <section>
            <h4 className="mb-2 text-[13px] font-semibold">Event timeline</h4>
            <ol className="space-y-1.5 border-l border-line pl-4">
              {data.events.map((e) => (
                <li key={e._id} className="relative text-[12px]">
                  <span className="absolute -left-[21px] top-1.5 h-2 w-2 rounded-full bg-line-2" />
                  <span className="text-ink-3">{fmtDateTime(e.at)}</span> · <span className="font-medium text-ink">{e.type}</span>{' '}
                  <span className="text-ink-3">{e.data ? Object.entries(e.data).filter(([, v]) => v !== undefined && v !== null).map(([k, v]) => `${k}: ${Array.isArray(v) ? v.join(', ') : v}`).join(' · ') : ''}</span>
                </li>
              ))}
            </ol>
          </section>
        </div>
      ) : null}
    </Drawer>
  );
}
